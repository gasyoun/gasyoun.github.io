    m = BY_SAN.get(key)
    if not m:
        print(f"!! конс. ключ не найден: {key}", file=sys.stderr); continue
    n = NUM[id(m)]
    san = esc(m["san"]); gl = esc(m["gloss"]); ruc = esc(ru)
    f = f'<a href="../fasmer-2026/original.html#{fas}">ст. {fas[1:]} #e{fas[1:]}</a>' if fas else "—"
    rows.append(
        f'<tr id="n{n}"><td>{n}</td><td><b>{ruc}</b></td>'
        f'<td>{san} <span class="gl">«{gl}»</span></td>'
        f'<td>{esc(yoga)}</td><td>{esc(podacha)}</td><td>{f}</td></tr>')

