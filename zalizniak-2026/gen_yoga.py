    ("DHĀ",   "де́ть",           "самадхи ⟨sam-ā-dhā⟩",                "Сам-ā-дхā = «вставленное внутрь»; деть — тот же корень", None),
    ("ÇRU",   "слыть",          "шрути ⟨çruti «услышанное»⟩",         "Слух, слушать, слыть — и çṛṇóti «слушает»", "e1065"),
    ("svayam","сам",            "свами ⟨svāmin «хозяин своего»⟩",     "svayam «сам» = сам; свамин — «владетель себя»", None),
