HERE = os.path.dirname(os.path.abspath(__file__))
sys.stdout.reconfigure(encoding="utf-8")

spec = importlib.util.spec_from_file_location("bp", os.path.join(HERE, "build_page.py"))
bp = importlib.util.module_from_spec(spec)
spec.loader.exec_module(bp)

NUM = {id(m): i for i, m in enumerate(bp.M, 1)}          # № статьи = enumerate(M,1)
BY_SAN = {}
for m in bp.M:
    key = re.sub(r"\s+", " ", m["san"]).split()[0]
    BY_SAN.setdefault(key, m)

def esc(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")

# (conspect-san-ключ, русское из конспекта, йога-слово ⟨добавка⟩, подача в зале, fasmer-якорь|None)
