    ("TAP",   "тёпло́ · топи́ть", "тапас ⟨tápas «жар»⟩",                "Аскеза = внутренний жар; tápati «нагревает» — дословно у Фасмера", "e922"),
    ("VID",   "ве́дать · ви́деть","видья, Веды ⟨⟩",                     "vidā́ «знание» — дословно в статье ведать", "e92"),
    ("JÑĀ",   "знать",          "джняна ⟨⟩",                          "Тот же корень *ǵneh₃-, что рус. знать", None),
    ("JĪV",   "живу́",           "джива ⟨⟩",                           "jīvati «живёт» = жить", "e361"),
    ("MAN",   "мню · па́мять",   "мантра ⟨man- «мыслить»⟩",            "Мантра = «орудие мысли»; родня — мнить, память", "e642"),
    ("dina‑", "день",           "Дьяус ⟨dyáus «небо-день»⟩",          "«День» и небо-Дьяус — одна пара *dyew-", "e265"),
    ("CAR",   "колесо́",         "чакра ⟨cakrá-⟩",                     "У Фасмера дословно: колесо… др.-инд. cakrás «колесо» — спорная пара закрыта 09-10", "e463"),
    ("agni‑", "ого́нь",          "агнихотра ⟨⟩",                       "agníḥ = огонь (и лат. ignis) — дословно у Фасмера", None),
