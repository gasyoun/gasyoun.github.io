#!/usr/bin/env python3
"""Summarize a Vale JSON report into a flag-rate table (H8384, ADR-0005).

Usage:
    vale --output=JSON . | python3 scripts/vale_flag_report.py
    python3 scripts/vale_flag_report.py vale-report.json

Prints counts per rule (alert level included) and, when run inside GitHub
Actions, appends the same table to $GITHUB_STEP_SUMMARY. Exit code is always 0
(prose linting is ADVISORY; blocking escalation is a later ruling).
"""
import collections
import json
import os
import sys

MD_HEADER = """# Vale EN-doc flag rate — {date}

_Auto-generated by `scripts/vale_flag_report.py` (H8384, ADR-0005). Advisory
baseline: counts only, CI stays green. Vale {vale} · base style {base}._

- **Files linted:** {files}
- **Total flags:** {flags} ({errors} errors / {warnings} warnings / {suggestions} suggestions)
- **Overall rate:** {rate} flags/file

## Counts per rule (top 20)

| Rule | Level | Flags |
|---|---|---|
"""


def main() -> int:
    raw = json.load(open(sys.argv[1]) if len(sys.argv) > 1 else sys.stdin)
    per_rule = collections.Counter()
    levels = {}
    files = set()
    sev = collections.Counter()
    for fname, alerts in raw.items():
        for a in alerts:
            if not isinstance(a, dict) or "Check" not in a:
                continue
            per_rule[a["Check"]] += 1
            levels.setdefault(a["Check"], a.get("Severity", "?"))
            sev[a.get("Severity", "?")] += 1
            files.add(fname)
    lines = []
    for rule, n in per_rule.most_common(20):
        lines.append(f"| {rule} | {levels[rule]} | {n} |")
    body = MD_HEADER.format(
        date=os.environ.get("FLAG_DATE", "run"),
        vale=os.environ.get("VALE_VERSION", "3.27.0"),
        base=os.environ.get("VALE_BASE", "-"),
        files=len(files),
        flags=sum(per_rule.values()),
        errors=sev.get("error", 0),
        warnings=sev.get("warning", 0),
        suggestions=sev.get("suggestion", 0),
        rate=round((sum(per_rule.values()) / len(files)) if files else 0, 1),
    ) + "\n".join(lines) + "\n"
    print(body)
    summary = os.environ.get("GITHUB_STEP_SUMMARY")
    if summary:
        with open(summary, "a", encoding="utf-8") as fh:
            fh.write(body)
    return 0


if __name__ == "__main__":
    sys.exit(main())
