#!/usr/bin/env python3
"""Archive the Wiktionary Sanskrit-etymology category tree.

Writes byte-faithful source snapshots to wiki/archive/raw/, a SHA-256
manifest, a human-readable SNAPSHOT.md, and data/lemmata.js plus
data/etymology.js / data/manifest.js for the static pages. Also folds the
cognate snapshot produced by fetch_cognates.py into the same checksum record.

    python3 wiki/scripts/fetch_snapshot.py             # full network refresh
    python3 wiki/scripts/fetch_snapshot.py --offline   # rebuild from raw/ only

Source: https://en.wiktionary.org/wiki/Category:Sanskrit_terms_by_etymology
Text is Wiktionary's (CC BY-SA); see Wiktionary:Copyrights.
"""
import hashlib
import html
import json
import re
import sys
import time
import urllib.parse
import urllib.request
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path

from etymology_meta import DESC, GRADES, lens_for

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "archive" / "raw"
DATA = ROOT / "data"
ARCH = ROOT / "archive"
RAW.mkdir(parents=True, exist_ok=True)
DATA.mkdir(parents=True, exist_ok=True)

BASE = "https://en.wiktionary.org"
CAT_TITLE = "Category:Sanskrit terms by etymology"
CAT_URL = BASE + "/wiki/Category:Sanskrit_terms_by_etymology"
API = BASE + "/w/api.php"
UA = "SanskritEtymologyArchive/1.0 (https://gasyoun.github.io/wiki/)"

# `--offline` rebuilds every derived file from the archived raw bytes, keeping the
# original snapshot timestamp so checksums stay reproducible with no network.
OFFLINE = "--offline" in sys.argv
if OFFLINE and (ARCH / "manifest.json").exists():
    NOW = json.loads((ARCH / "manifest.json").read_text(encoding="utf-8"))["created_at_utc"]
else:
    NOW = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
STAMP = NOW[:10]


def get(url):
    req = urllib.request.Request(
        url, headers={"User-Agent": UA, "Accept-Encoding": "identity"}
    )
    with urllib.request.urlopen(req, timeout=60) as resp:
        return resp.read()


def api(params):
    params = dict(params, action="query", format="json", formatversion="2")
    return get(API + "?" + urllib.parse.urlencode(params))


def cat_url(title):
    if not title.startswith("Category:"):
        title = "Category:" + title
    return BASE + "/wiki/" + urllib.parse.quote(title.replace(" ", "_"), safe="_-:")


def word_url(deva):
    return BASE + "/wiki/" + urllib.parse.quote(deva, safe="") + "#Sanskrit"


def write_raw(name, payload, source):
    path = RAW / name
    path.write_bytes(payload)
    return {
        "file": "raw/" + name,
        "bytes": len(payload),
        "sha256": hashlib.sha256(payload).hexdigest(),
        "source": source,
        "fetched_at_utc": NOW,
    }


def obtain(name, url):
    """Fetch a raw source, or replay the archived bytes in --offline mode."""
    if OFFLINE:
        return (RAW / name).read_bytes()
    return get(url)


def entry_for(relpath, source, fetched_at=None):
    """Checksum a file we did not fetch in this run (generated by a sibling script)."""
    payload = (ARCH / relpath).read_bytes()
    return {
        "file": relpath,
        "bytes": len(payload),
        "sha256": hashlib.sha256(payload).hexdigest(),
        "source": source,
        "fetched_at_utc": fetched_at or NOW,
    }


def parse_counts(page_html):
    """Read (N c, M e) from the CategoryTree markup in the raw page."""
    result = {}
    if isinstance(page_html, bytes):
        page_html = page_html.decode("utf-8", "replace")
    for li in re.findall(r"<li>.*?</li>", page_html, re.S):
        link = re.search(r'<a href="/wiki/(Category:[^"]+)" title="Category:([^"]+)"', li)
        count = re.search(r"\((\d+) c, (\d+) e\)", li)
        if not (link and count):
            continue
        title = html.unescape(link.group(2))
        result[title] = {"c": int(count.group(1)), "e": int(count.group(2))}
    return result


def members_of(title):
    params = {
        "list": "categorymembers",
        "cmtitle": title,
        "cmtype": "subcat|page",
        "cmlimit": "500",
    }
    out, cont = [], None
    while True:
        q = dict(params)
        if cont:
            q["cmcontinue"] = cont
        data = json.loads(api(q))
        out.extend({"ns": m["ns"], "title": m["title"]} for m in data["query"]["categorymembers"])
        cont = data.get("continue", {}).get("cmcontinue")
        if not cont or len(out) >= 20000:
            break
    return out


def build_lemmata(tree, categories, snapshot_id):
    """Invert the category tree into a searchable word/source index.

    `words` keeps the real overlaps: a word appearing in three of the 42
    categories carries all three indices. `nested` holds the 2,005 second-level
    buckets (PIE roots, donor languages, suffixes, prefixes) with their parent.
    Nothing is invented — both lists are verbatim category-member titles.
    """
    index = {c["name"]: i for i, c in enumerate(categories)}
    memberships = defaultdict(list)
    reconstructions = set()
    nested, other = [], []
    for parent, members in tree.items():
        pi = index[parent]
        for m in members:
            title, ns = m["title"], m["ns"]
            if ns == 14:
                short = title[len("Category:"):] if title.startswith("Category:") else title
                nested.append([short, pi])
            elif ns in (0, 118):
                memberships[title].append(pi)
                if ns == 118:
                    reconstructions.add(title)
            else:
                # Template: documentation pages and similar; kept, never discarded.
                other.append([title, pi, ns])
    words = [[w, sorted(set(ids)), 1 if w in reconstructions else 0]
             for w, ids in sorted(memberships.items())]
    nested.sort(key=lambda x: (x[0].casefold(), x[0]))
    other.sort(key=lambda x: (x[0].casefold(), x[0]))
    payload = {
        "snapshotId": snapshot_id,
        "fetchedAtUtc": NOW,
        "base": BASE,
        "categories": categories,
        "words": words,
        "nested": nested,
        "other": other,
        "totals": {
            "categories": len(categories),
            "uniqueWords": len(words),
            "memberships": sum(len(ids) for _, ids, _ in words),
            "crossListed": sum(1 for _, ids, _ in words if len(ids) > 1),
            "reconstructed": len(reconstructions),
            "nested": len(nested),
            "other": len(other),
        },
    }
    (DATA / "lemmata.js").write_text(
        "window.ETYMOLOGY_LEMMATA = " +
        json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8")
    return payload["totals"]



def main():
    manifest = []

    page = obtain("category.html", CAT_URL)
    manifest.append(write_raw("category.html", page, CAT_URL))
    counts = parse_counts(page)
    if len(counts) != 42:
        raise SystemExit("expected 42 subcategories, parsed %d" % len(counts))

    sub_params = {"action": "query", "list": "categorymembers", "cmtitle": CAT_TITLE,
                  "cmtype": "subcat", "cmlimit": "500", "format": "json"}
    sub_url = API + "?" + urllib.parse.urlencode(sub_params)
    subs = (RAW / "subcategories.json").read_bytes() if OFFLINE else api(
        {k: v for k, v in sub_params.items() if k != "format"})
    manifest.append(write_raw("subcategories.json", subs, sub_url))

    wt_url = API + "?" + urllib.parse.urlencode(
        {"action": "parse", "page": CAT_TITLE, "prop": "wikitext", "format": "json"})
    manifest.append(write_raw("category-wikitext.json", obtain("category-wikitext.json", wt_url), wt_url))

    rt_url = API + "?" + urllib.parse.urlencode(
        {"action": "parse", "page": CAT_TITLE, "prop": "text", "format": "json",
         "formatversion": "2"})
    manifest.append(write_raw("category-rendered.json", obtain("category-rendered.json", rt_url), rt_url))

    titles = sorted(counts)
    if OFFLINE:
        tree_payload = (RAW / "subcategory-members.json").read_bytes()
        tree = json.loads(tree_payload)["categories"]
    else:
        tree = {}
        for i, title in enumerate(titles, 1):
            tree[title] = members_of("Category:" + title)
            print("[%02d/42] %-70s %5d members" % (i, title[:70], len(tree[title])), flush=True)
            time.sleep(0.12)
        tree_payload = json.dumps(
            {"fetched_at_utc": NOW, "parent": CAT_URL, "categories": tree},
            ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    manifest.append(write_raw(
        "subcategory-members.json", tree_payload,
        [API + "?list=categorymembers&cmtitle=" + urllib.parse.quote(t) for t in titles]))

    # fetch_cognates.py writes these two; keep them under the same SHA-256 record.
    cog_fetched = NOW
    if (RAW / "cognates.json").exists():
        cog_fetched = json.loads((RAW / "cognates.json").read_text(encoding="utf-8"))["fetched_at_utc"]
        manifest.append(entry_for(
            "raw/cognates.json",
            API + " (per-language PIE root/word categories; full URL list in cognates-manifest.json)",
            cog_fetched))
    if (ARCH / "cognates-manifest.json").exists():
        manifest.append(entry_for(
            "cognates-manifest.json",
            "Generated by wiki/scripts/fetch_cognates.py — one entry per queried Wiktionary category",
            cog_fetched))

    categories = []
    for t in titles:
        categories.append({
            "name": t, "url": cat_url(t), "c": counts[t]["c"], "e": counts[t]["e"],
            "lens": lens_for(t), "desc": DESC.get(t, "Terms grouped by this etymological type."),
        })

    lemmata_totals = build_lemmata(tree, categories, "sanskrit-etymology-" + STAMP)
    cog_items = cog_layers = 0
    if (RAW / "cognates.json").exists():
        cog = json.loads((RAW / "cognates.json").read_text(encoding="utf-8"))
        cog_items, cog_layers = len(cog["items"]), len(cog["layers"])

    doc = {
        "snapshot_id": "sanskrit-etymology-" + STAMP,
        "created_at_utc": NOW,
        "source": {
            "category_page": CAT_URL,
            "api": API,
            "rights": "Wiktionary text is CC BY-SA; see "
                      "https://en.wiktionary.org/wiki/Wiktionary:Copyrights",
        },
        "purpose": "Restorable backup of the source taxonomy if the Wiktionary "
                   "category is moved, renamed or lost.",
        "totals": {"subcategories": len(categories),
                   "direct_members_captured": sum(len(v) for v in tree.values()),
                   "unique_words": lemmata_totals["uniqueWords"],
                   "nested_categories": lemmata_totals["nested"],
                   "cognate_sets": cog_items,
                   "inheritance_layers": cog_layers},
        "files": manifest,
    }
    (ARCH / "manifest.json").write_text(
        json.dumps(doc, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (DATA / "manifest.js").write_text(
        "window.ETYMOLOGY_MANIFEST = " + json.dumps(doc, ensure_ascii=False) + ";\n",
        encoding="utf-8")

    for g in GRADES:
        g["rootUrl"] = word_url(g["root"]) if g["root"] else ""
        g["gunaUrl"] = word_url(g["gunaWord"]) if g["gunaWord"] else ""
        g["vrddhiUrl"] = word_url(g["vrddhiWord"]) if g["vrddhiWord"] else ""
    payload = {
        "snapshotId": doc["snapshot_id"], "fetchedAtUtc": NOW,
        "categoryUrl": CAT_URL, "categories": categories, "grades": GRADES,
        "sourceLinks": {
            "vrddhi": cat_url("Category:Sanskrit vrddhi derivatives"),
            "roots": cat_url("Category:Sanskrit roots"),
            "pieRoots": cat_url("Category:Sanskrit terms by Proto-Indo-European root"),
            "unknown": cat_url("Category:Sanskrit terms with unknown etymologies"),
            "copyrights": "https://en.wiktionary.org/wiki/Wiktionary:Copyrights",
        },
    }
    (DATA / "etymology.js").write_text(
        "window.ETYMOLOGY = " + json.dumps(payload, ensure_ascii=False, indent=1) + ";\n",
        encoding="utf-8")

    lines = [
        "# Source snapshot — Sanskrit terms by etymology", "",
        "Snapshot `%s`, taken %s." % (doc["snapshot_id"], NOW), "",
        "Byte-faithful backup of [%s](%s) and its 42 subcategories, including"
        % (CAT_TITLE, CAT_URL),
        "every direct member one level down (%d titles)."
        % doc["totals"]["direct_members_captured"], "",
        "The parent category contains **no word pages at all** — only subcategories —"
        " so a backup",
        "of the parent page alone would preserve the labels but none of the words.",
        "See [manifest.json](manifest.json) for SHA-256 checksums and source URLs.",
        "", "## Raw files", "",
        "| File | Bytes | SHA-256 |", "| --- | ---: | --- |",
    ]
    for f in manifest:
        lines.append("| [`%s`](%s) | %d | `%s` |"
                     % (f["file"].split("/")[-1], f["file"], f["bytes"], f["sha256"]))
    lines += ["", "## The 42 subcategories", "",
              "`c` = subcategories, `e` = word pages. Both are as displayed on the"
              " source page at snapshot time.", "",
              "| Subcategory | c | e |", "| --- | ---: | ---: |"]
    for cat in categories:
        lines.append("| [%s](%s) | %d | %d |" % (cat["name"], cat["url"], cat["c"], cat["e"]))
    lines += ["", "## Category descriptions (source page intro)", ""]
    for name in sorted(DESC):
        lines.append("- **%s** — %s" % (name, DESC[name]))
    lines += [
        "", "## Derived teaching data", "",
        "Rebuilt from the raw files above; no extra network access needed.", "",
        "| File | Contents |", "| --- | --- |",
        "| [`data/etymology.js`](../data/etymology.js) | 42 categories with `c`/`e`"
        " counts, lens grouping, descriptions and the guṇa/vṛddhi grades. |",
        "| [`data/lemmata.js`](../data/lemmata.js) | %s unique word lemmata with"
        " their %s category memberships, plus %s second-level source buckets"
        " (PIE roots, donor languages, suffixes, prefixes). |"
        % tuple(format(lemmata_totals[k], ",") for k in
                ("uniqueWords", "memberships", "nested")),
        "| [`data/cognates.js`](../data/cognates.js) | %d PIE root/word sets across 8"
        " languages and %d inheritance layers, drawn from %s queried Wiktionary"
        " categories. |" % (cog_items, cog_layers,
                            format(len(json.loads((ARCH / "cognates-manifest.json").read_text(
                                encoding="utf-8"))["source_urls"])
                                  if (ARCH / "cognates-manifest.json").exists() else 0, ",")),
        "| [`cognates-manifest.json`](cognates-manifest.json) | Exact source"
        " URL of every category used to build the cognate data. |", "",
        "The crawl is **one level deep**: it captures direct members of the 42"
        " subcategories, not the full contents of the %s nested buckets. The"
        " explorer therefore presents a faithful sample, not a complete lexicon."
        % format(lemmata_totals["nested"], ","), "",
        "## Rights", "",
        "Wiktionary text is available under CC BY-SA; see"
        " [Wiktionary:Copyrights](%s)." % payload["sourceLinks"]["copyrights"],
        "This snapshot reproduces category names and counts for teaching and"
        " citation, with a link back to the original on every item.", "",
        "Regenerate with `python3 wiki/scripts/fetch_snapshot.py`. Run"
        " `fetch_cognates.py` first if the cognate sets need refreshing. Add"
        " `--offline` to rebuild every derived file from this snapshot alone,"
        " preserving the original timestamp and checksums.", "",
    ]
    (ARCH / "SNAPSHOT.md").write_text("\n".join(lines), encoding="utf-8")

    print("OK: %d categories, %d members, %d raw files" %
          (len(categories), doc["totals"]["direct_members_captured"], len(manifest)))


if __name__ == "__main__":
    main()
